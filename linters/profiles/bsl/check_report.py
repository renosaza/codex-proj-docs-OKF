#!/usr/bin/env python3
"""Fail CI on BSL Language Server findings or an invalid/empty JSON report."""

import argparse
import json
import sys
from pathlib import Path


def validate_report(report: object) -> tuple[int, list[str]]:
    """Validate the required report shape and return its files and findings."""
    if not isinstance(report, dict):
        raise ValueError("report must be a JSON object")
    files = report.get("fileinfos")
    if not isinstance(files, list) or not files:
        raise ValueError("fileinfos must be a non-empty array")
    findings: list[str] = []
    for item in files:
        if (
            not isinstance(item, dict)
            or not isinstance(item.get("path"), str)
            or not item["path"].strip()
        ):
            raise ValueError("each file must have a non-empty path")
        diagnostics = item.get("diagnostics")
        if not isinstance(diagnostics, list):
            raise ValueError(f"{item['path']}: diagnostics must be an array")
        for diagnostic in diagnostics:
            if not isinstance(diagnostic, dict):
                raise ValueError(f"{item['path']}: diagnostic must be an object")
            severity = diagnostic.get("severity")
            if severity not in ("Error", "Warning", "Information", "Hint"):
                raise ValueError(f"{item['path']}: invalid or missing diagnostic severity")
            message = diagnostic.get("message")
            if not isinstance(message, str) or not message.strip():
                raise ValueError(f"{item['path']}: invalid or missing diagnostic message")
            findings.append(f"{item['path']}: {severity}: {message}")
    return len(files), findings


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("report", type=Path, help="fresh bsl-json.json generated by this CI run")
    args = parser.parse_args()
    try:
        report = json.loads(args.report.read_text(encoding="utf-8-sig"))
        file_count, findings = validate_report(report)
    except (OSError, UnicodeError, ValueError) as error:
        print(f"Invalid BSL report: {error}", file=sys.stderr)
        return 2
    for finding in findings:
        print(finding)
    print(f"BSL: {file_count} files, {len(findings)} diagnostics")
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
